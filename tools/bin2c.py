#!/usr/bin/env python3
"""Deterministic binary-to-header compiler; no generated global pointers."""
from pathlib import Path
import argparse
import hashlib
import re

def header(data, symbol):
    if not re.fullmatch(r'[A-Za-z_]\w*', symbol):
        raise ValueError('invalid C identifier')
    guard='metalmax_bin2c_'+symbol.lower()+'_h'
    rows=[','.join('0x%02x'%v for v in data[i:i+24])+',' for i in range(0,len(data),24)]
    return ('// Generated by tools/bin2c.py. SHA256 '+hashlib.sha256(data).hexdigest()+'\n'
            '#ifndef '+guard+'\n#define '+guard+'\n#include <stdint.h>\n'
            'alignas(4) static const uint8_t '+symbol+'[] = {\n'+'\n'.join(rows or ['0'])+'\n};\n'
            'static constexpr unsigned '+symbol+'_size = '+str(len(data))+';\n#endif\n')

def write(data, path, symbol):
    path=Path(path);path.parent.mkdir(parents=True,exist_ok=True)
    text=header(data,symbol)
    if not path.exists() or path.read_text()!=text:path.write_text(text)

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('binary',type=Path);p.add_argument('header',type=Path);p.add_argument('--symbol',required=True)
    a=p.parse_args();write(a.binary.read_bytes(),a.header,a.symbol)
